//! Builds the ground-truth files in /data from the astronomical calendar, never from the
//! arithmetic algorithm under test, so the data is an independent check.

use crate::fixed::{self, RD_TO_JDN};
use crate::persian::{self, days_before_month, month_length, weekday};
use std::collections::BTreeSet;
use std::fmt::Write;

pub const FIRST_YEAR: i64 = 1178;
pub const LAST_YEAR: i64 = 3000;
const GENERATOR: &str = "tools/calendar-data";

/// Nowruz (R.D.) of FIRST_YEAR ..= LAST_YEAR + 1, index 0 = FIRST_YEAR.
pub struct Nowruz(Vec<i64>);

impl Nowruz {
    pub fn compute() -> Self {
        Nowruz((FIRST_YEAR..=LAST_YEAR + 1).map(persian::nowruz).collect())
    }
    pub fn of(&self, year: i64) -> i64 {
        self.0[(year - FIRST_YEAR) as usize]
    }
    pub fn is_leap(&self, year: i64) -> bool {
        self.of(year + 1) - self.of(year) == 366
    }
}

fn iso(rd: i64) -> String {
    let (y, m, d) = fixed::to_gregorian(rd);
    format!("{y:04}-{m:02}-{d:02}")
}

/// Checks the astronomical calendar against the official leap-year table
/// (data/official/kabise-1206-1498.txt). Returns the number of years compared.
pub fn check_official(table: &str, nowruz: &Nowruz) -> Result<usize, String> {
    let mut count = 0;
    for line in table.lines().map(str::trim) {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (year, date) = line
            .split_once(char::is_whitespace)
            .ok_or(format!("bad line: {line}"))?;
        let year: i64 = year
            .trim_end_matches('*')
            .parse()
            .map_err(|_| format!("bad year: {line}"))?;
        let date = date.trim();
        if iso(nowruz.of(year)) != date {
            return Err(format!(
                "astronomical Nowruz of {year} is {}, official table says {date}",
                iso(nowruz.of(year))
            ));
        }
        count += 1;
    }
    Ok(count)
}

fn rule33(year: i64) -> bool {
    (25 * year + 11).rem_euclid(33) < 8
}

/// Returns (file name, content) pairs.
pub fn build(nowruz: &Nowruz) -> Result<Vec<(&'static str, String)>, String> {
    let years = FIRST_YEAR..=LAST_YEAR;
    let mut files = Vec::new();

    let mut s =
        String::from("year,is_leap,days_in_year,nowruz_gregorian,nowruz_jdn,nowruz_weekday\n");
    for y in years.clone() {
        let leap = nowruz.is_leap(y);
        let jdn = nowruz.of(y) + RD_TO_JDN;
        writeln!(
            s,
            "{y},{},{},{},{jdn},{}",
            leap as u8,
            365 + leap as u8 as i64,
            iso(nowruz.of(y)),
            weekday(jdn)
        )
        .unwrap();
    }
    files.push(("years.csv", s));

    let mut s = format!(
        "# Leap years of the Solar Hijri (Persian) calendar, {FIRST_YEAR}-{LAST_YEAR} AP.\n\
         # Source: astronomical calculation on the 52.5 E meridian (tools/calendar-data).\n\
         # 1206-1498 AP match the official table of the University of Tehran Calendar Center.\n\
         # Generated by {GENERATOR} - do not edit by hand.\n"
    );
    for y in years.clone().filter(|&y| nowruz.is_leap(y)) {
        writeln!(s, "{y}").unwrap();
    }
    files.push(("leap-years.txt", s));

    // Years where the 33-year rule says "leap" but the real calendar does not; in each case the
    // following year is leap instead. Any other kind of disagreement is an error.
    let mut corrections = Vec::new();
    for y in years.clone() {
        let leap = nowruz.is_leap(y);
        if rule33(y) == leap {
            continue;
        }
        let next_is_leap = y + 1 > LAST_YEAR || nowruz.is_leap(y + 1);
        if rule33(y) && !leap && !rule33(y + 1) && next_is_leap {
            corrections.push(y);
        } else if !(!rule33(y) && leap && corrections.last() == Some(&(y - 1))) {
            return Err(format!("unexpected deviation pattern at {y}"));
        }
    }
    let mut s = format!(
        "# Years (AP) that the 33-year rule (25*y + 11) mod 33 < 8 marks as leap but that are\n\
         # NOT leap in the real calendar; in each case the following year IS leap instead.\n\
         # Valid for {FIRST_YEAR}-{LAST_YEAR} AP. Generated by {GENERATOR}.\n"
    );
    for y in &corrections {
        writeln!(s, "{y}").unwrap();
    }
    files.push(("corrections.txt", s));

    // First/last day of every year, 29 and 30 Esfand of leap years, and the first/last day of
    // every month in 1300-1500 AP.
    let mut rows = BTreeSet::new();
    let mut add = |y: i64, m: i64, d: i64| {
        let rd = nowruz.of(y) + days_before_month(m) + d - 1;
        let (gy, gm, gd) = fixed::to_gregorian(rd);
        let jdn = rd + RD_TO_JDN;
        rows.insert((y, m, d, gy, gm, gd, jdn, weekday(jdn)));
    };
    for y in years.clone() {
        let leap = nowruz.is_leap(y);
        add(y, 1, 1);
        add(y, 12, month_length(12, leap));
        if leap {
            add(y, 12, 29);
        }
    }
    for y in 1300..=1500 {
        let leap = nowruz.is_leap(y);
        for m in 1..=12 {
            add(y, m, 1);
            add(y, m, month_length(m, leap));
        }
    }
    let mut s = String::from("jy,jm,jd,gy,gm,gd,jdn,weekday\n");
    for (y, m, d, gy, gm, gd, jdn, wd) in rows {
        writeln!(s, "{y},{m},{d},{gy},{gm},{gd},{jdn},{wd}").unwrap();
    }
    files.push(("test-vectors.csv", s));

    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_official_table_and_repository_data() {
        let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../../data/");
        let nowruz = Nowruz::compute();
        let table =
            std::fs::read_to_string(format!("{root}official/kabise-1206-1498.txt")).unwrap();
        assert_eq!(check_official(&table, &nowruz), Ok(293));
        for (name, content) in build(&nowruz).unwrap() {
            let on_disk = std::fs::read_to_string(format!("{root}{name}")).unwrap();
            assert_eq!(
                content, on_disk,
                "{name} is out of date; run `cargo run --release`"
            );
        }
    }
}

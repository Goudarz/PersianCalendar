//! Scores third-party libraries (tools/library-evaluation/results/*.txt) against data/years.csv
//! and renders results/SUMMARY.md.
//!
//! A results file starts with "# <library name>" and has one "<year> <YYYY-MM-DD>" line per
//! Persian year: the Gregorian date the library gives for 1 Farvardin. An optional
//! "<same name>.everyday.json" holds {"days", "g2pWrong", "p2gWrong"} counts.

use std::collections::HashMap;
use std::fs;
use std::path::Path;

fn truth(years_csv: &str) -> HashMap<i64, String> {
    years_csv
        .lines()
        .skip(1)
        .filter_map(|l| {
            let f: Vec<&str> = l.split(',').collect();
            Some((f.first()?.parse().ok()?, f.get(3)?.to_string()))
        })
        .collect()
}

fn json_number(json: &str, key: &str) -> Option<i64> {
    let rest = &json[json.find(&format!("\"{key}\""))? + key.len() + 2..];
    let value = rest.trim_start().strip_prefix(':')?.trim_start();
    let end = value
        .find(|c: char| !c.is_ascii_digit())
        .unwrap_or(value.len());
    value[..end].parse().ok()
}

fn json_string(json: &str, key: &str) -> Option<String> {
    let rest = &json[json.find(&format!("\"{key}\""))? + key.len() + 2..];
    let value = rest
        .trim_start()
        .strip_prefix(':')?
        .trim_start()
        .strip_prefix('"')?;
    Some(value[..value.find('"')?].to_string())
}

struct Row {
    name: String,
    correct: String,
    wrong: String,
    everyday: String,
    upper: i64,
}

pub fn summary(years_csv: &str, results_dir: &Path) -> Result<String, String> {
    let truth = truth(years_csv);
    let mut rows = Vec::new();
    let mut paths: Vec<_> = fs::read_dir(results_dir)
        .map_err(|e| format!("{}: {e}", results_dir.display()))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "txt"))
        .collect();
    paths.sort();
    for path in paths {
        let text = fs::read_to_string(&path).map_err(|e| e.to_string())?;
        let mut name = path.file_stem().unwrap().to_string_lossy().to_string();
        let mut dates = HashMap::new();
        for line in text.lines() {
            if let Some(n) = line.strip_prefix('#') {
                name = n.trim().to_string();
            } else if let Some((y, d)) = line.split_once(' ') {
                if let Ok(y) = y.parse::<i64>() {
                    dates.insert(y, d.trim().to_string());
                }
            }
        }
        let ok = |y: i64| truth.get(&y).is_some_and(|t| dates.get(&y) == Some(t));
        let (correct, upper) = if ok(1404) {
            let (mut lo, mut hi) = (1404, 1404);
            while ok(lo - 1) {
                lo -= 1;
            }
            while ok(hi + 1) {
                hi += 1;
            }
            (format!("{lo}–{hi}"), hi)
        } else {
            ("**wrong for 1404**".to_string(), 0)
        };
        let wrong: Vec<String> = (1300..=1600)
            .filter(|y| dates.get(y).is_some_and(|d| Some(d) != truth.get(y)))
            .map(|y| y.to_string())
            .collect();
        let wrong = match wrong.len() {
            0 => "–".to_string(),
            1..=6 => wrong.join(", "),
            _ => format!("{} …", wrong[..6].join(", ")),
        };
        let everyday_path = path.with_extension("everyday.json");
        let everyday = match fs::read_to_string(&everyday_path) {
            Ok(json) => {
                let g2p = json_number(&json, "g2pWrong").map_or("?".into(), |n| n.to_string());
                let p2g = json_number(&json, "p2gWrong").map_or("–".into(), |n| n.to_string());
                match json_string(&json, "range") {
                    Some(range) => format!("{g2p} / {p2g} (only {range})"),
                    None => format!("{g2p} / {p2g}"),
                }
            }
            Err(_) => "not measured".to_string(),
        };
        rows.push(Row {
            name,
            correct,
            wrong,
            everyday,
            upper,
        });
    }
    rows.sort_by(|a, b| {
        b.upper
            .cmp(&a.upper)
            .then(a.name.to_lowercase().cmp(&b.name.to_lowercase()))
    });

    let mut out = String::from(
        "# Library evaluation results · نتایج ارزیابی کتابخانه‌ها\n\n\
         Generated by `tools/calendar-data` (`score-libraries`). Ground truth: `data/years.csv`\n\
         (astronomical calendar on the 52.5° E meridian; matches the official table for 1206–1498 AP).\n\n\
         * **Correct years**: the unbroken range of Persian years around 1404 for which the library's\n  \
         1 Farvardin is correct (the ground truth covers 1178–3000).\n\
         * **Wrong years 1300–1600**: years whose 1 Farvardin is wrong.\n\
         * **Every day 1300–1500**: wrong conversions over all 73,414 days, Gregorian→Persian / Persian→Gregorian\n  \
         (only measured for some libraries).\n\n\
         <div dir=\"rtl\">\n\n\
         این جدول به صورت خودکار توسط ابزار `tools/calendar-data` (با دستور `score-libraries`) و بر مبنای دادهٔ مرجع نجومی در `data/years.csv` ساخته شده است:\n\n\
         * **بازهٔ سال‌های درست (Correct years):** بازهٔ پیوستهٔ سال‌های شمسی (حول‌وحوش سال ۱۴۰۴) که در اون تاریخ ۱ فروردینِ کتابخونه کاملا درسته (بازهٔ مرجع ما سال‌های ۱۱۷۸ تا ۳۰۰۰ رو پوشش می‌ده).\n\
         * **سال‌های اشتباه در ۱۳۰۰ تا ۱۶۰۰ (Wrong years 1300–1600):** سال‌هایی در این بازه که کتابخونه روز اول فروردین رو براشون اشتباه حساب می‌کنه.\n\
         * **تست تک‌تک روزهای ۱۳۰۰ تا ۱۵۰۰ (Every day 1300–1500):** تعداد روزهای اشتباه در تبدیل تمام ۷۳٬۴۱۴ روز این دویست سال، به تفکیکِ «میلادی به شمسی / شمسی به میلادی».\n\n\
         </div>\n\n\
         | Library | Correct years | Wrong years 1300–1600 | Every day 1300–1500 (G→P / P→G) |\n\
         |---|---|---|---|\n",
    );
    for r in rows {
        out.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            r.name, r.correct, r.wrong, r.everyday
        ));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::{json_number, json_string};

    #[test]
    fn reads_json_numbers() {
        let j = r#"{"library": "x", "days": 73414, "g2pWrong": 2940, "p2gWrong": null}"#;
        assert_eq!(json_number(j, "g2pWrong"), Some(2940));
        assert_eq!(json_number(j, "p2gWrong"), None);
        assert_eq!(
            json_string(r#"{"range": "1304-1500"}"#, "range").as_deref(),
            Some("1304-1500")
        );
    }
}

// Writes data/locale-names.json: month and weekday names of the Persian calendar from CLDR
// (via the ICU data built into Node.js). Run: node tools/generate_locale_data.mjs
import { writeFileSync } from 'node:fs'

const locales = {
  'fa-IR': 'Persian (Iran)',
  'fa-AF': 'Dari (Afghanistan)',
  'ps-AF': 'Pashto (Afghanistan)',
  'ckb-IR': 'Central Kurdish (Iran)',
  en: 'English',
  ar: 'Arabic',
  tr: 'Turkish',
  az: 'Azerbaijani',
  de: 'German',
  fr: 'French',
  ru: 'Russian',
}
// Any Persian year works: take 1404, whose 1 Farvardin is 2025-03-21.
const nowruz = Date.UTC(2025, 2, 21, 12)
const dayMs = 864e5
const monthStart = (m) => new Date(nowruz + (m < 6 ? m * 31 : 186 + (m - 6) * 30) * dayMs + 5 * dayMs)
const out = {
  source: `CLDR ${process.versions.cldr} (ICU ${process.versions.icu}), generated by tools/generate_locale_data.mjs`,
  note: 'months[0] = Farvardin; weekdays[0] = Saturday (first day of the week in Iran and Afghanistan). ' +
    "'format' is the form used inside a date (e.g. '1 Farvardin'), 'standalone' is the form used on its own.",
  locales: {},
}
for (const [tag, label] of Object.entries(locales)) {
  const names = (opts, dates) => dates.map((d) => new Intl.DateTimeFormat(`${tag}-u-ca-persian`, { ...opts, timeZone: 'UTC' }).format(d))
  const monthDates = [...Array(12).keys()].map(monthStart)
  // formatToParts on a full date gives the "format" form of the month name
  const formatMonths = monthDates.map((d) => new Intl.DateTimeFormat(`${tag}-u-ca-persian`, { day: 'numeric', month: 'long', timeZone: 'UTC' })
    .formatToParts(d).find((p) => p.type === 'month').value)
  const weekDates = [...Array(7).keys()].map((i) => new Date(Date.UTC(2025, 2, 22 + i))) // 2025-03-22 is a Saturday
  out.locales[tag] = {
    label,
    months: { format: formatMonths, standalone: names({ month: 'long' }, monthDates) },
    monthsShort: names({ month: 'short' }, monthDates),
    weekdays: names({ weekday: 'long' }, weekDates),
    weekdaysShort: names({ weekday: 'short' }, weekDates),
    era: new Intl.DateTimeFormat(`${tag}-u-ca-persian`, { era: 'short', year: 'numeric', timeZone: 'UTC' })
      .formatToParts(monthDates[0]).find((p) => p.type === 'era')?.value ?? null,
  }
}
writeFileSync(new URL('../data/locale-names.json', import.meta.url), JSON.stringify(out, null, 2) + '\n')
console.log(out.source)
